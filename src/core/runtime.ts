/**
 * 執行期注入層（Runtime i18n Overlay）的主行程端工具：
 *
 * 1. {@link buildRuntimeScript}：把 renderer 端的 overlay 函式序列化，連同詞庫
 *    寫成 asar 內的 `antigravity-i18n-runtime.js`。
 * 2. {@link injectHook}：在 Electron 主行程入口（package.json 的 `main`）最前面
 *    插入一小段掛鉤，於 `web-contents-created` → `dom-ready` 時以
 *    `webContents.executeJavaScript()` 注入 runtime。
 *
 * 3. 同一個掛鉤也負責自訂背景圖：每次 `dom-ready` 讀取 `background.json`，
 *    所以換圖不需要重新打包 app.asar。
 *
 * 掛鉤前後有明確標記，可偵測與移除；還原則一律以原始 app.asar 備份覆蓋。
 */

export const RUNTIME_FILE_NAME = 'antigravity-i18n-runtime.js';
export const HOOK_BEGIN = '/* antigravity-i18n:runtime-hook:begin */';
export const HOOK_END = '/* antigravity-i18n:runtime-hook:end */';
export const RUNTIME_MARKER = '/* antigravity-i18n:runtime */';
/**
 * 掛鉤版本：
 * - 1：翻譯 runtime
 * - 2：翻譯 runtime + 自訂背景圖
 * - 3：背景圖支援內建漸層預設（bg preset）與可讀性遮罩（--tint）
 * - 4：介面內背景設定面板（Ctrl+Alt+B），設定存於 IndexedDB
 * - 5：面板新增「掃描未翻譯英文」（複製 JSON、前往 GitHub 回報）
 * - 6：桌布收藏夾與自動輪播、外觀微調（CJK 字型、毛玻璃）、四語 runtime 與面板內五語即時切換
 * - 7：面板自身五語系化（文案表以 panelCfg.i18n 傳入，跟隨顯示語系或瀏覽器語系）
 */
export const HOOK_VERSION = 7;

/** 介面面板選圖的大小上限（與 CLI 相同） */
export const PANEL_MAX_BYTES = 10 * 1024 * 1024;

export type ModuleFormat = 'cjs' | 'esm';

export interface RuntimeLayerInfo {
  enabled: boolean;
  /** 隨 runtime 載入的詞彙條數 */
  entries: number;
  /** 其中含佔位符（以正規表示式比對）的條數 */
  patternEntries: number;
  /** 掛鉤所在的主行程入口（asar 內相對路徑） */
  mainEntry?: string;
  /** runtime 檔案（asar 內相對路徑） */
  runtimeFile?: string;
  format?: ModuleFormat;
  /** 是否載入翻譯 runtime（僅背景模式為 false） */
  translation?: boolean;
  /** runtime 內打包的語系（面板可免重整切換） */
  langs?: Lang[];
  /** 未啟用的原因 */
  reason?: string;
}

export interface HookOptions {
  /**
   * 是否讀取並注入翻譯 runtime（預設 true）。
   * 僅背景模式（--lang none）為 false：不讀 runtime 檔，只負責背景與介面面板。
   */
  translate?: boolean;
}

const PLACEHOLDER_RE = /\{[A-Za-z_][A-Za-z0-9_]*\}|%[sd]/;

/** 篩選出要隨 runtime 載入的詞條（排除原文與譯文相同者） */
export function runtimeDictionary(dict: Dictionary): Dictionary {
  const out: Dictionary = {};
  for (const [k, v] of Object.entries(dict)) if (k && v && k !== v) out[k] = v;
  return out;
}

export function countRuntimeEntries(dict: Dictionary): { entries: number; patternEntries: number } {
  const d = runtimeDictionary(dict);
  const keys = Object.keys(d);
  return { entries: keys.length, patternEntries: keys.filter((k) => PLACEHOLDER_RE.test(k)).length };
}

export type RuntimeDicts = Partial<Record<Lang, Dictionary>>;

/**
 * 把多個語系的詞庫打包成共享 key 的精簡結構：
 * `{ keys: [...], langs: { 'zh-TW': [...], 'zh-CN': [...] } }`，各語系陣列與 keys 等長，沒有譯文為 null。
 * 語系依 LANGS 的順序排列，輸出穩定（相同輸入產生相同的 runtime 檔）。
 */
export function buildRuntimePack(dicts: RuntimeDicts): RuntimePack {
  const langs = LANGS.filter((l) => dicts[l] !== undefined);
  const cleaned = Object.fromEntries(langs.map((l) => [l, runtimeDictionary(dicts[l]!)])) as Record<Lang, Dictionary>;
  const keys: string[] = [];
  const seen = new Set<string>();
  for (const l of langs) {
    for (const k of Object.keys(cleaned[l])) {
      if (!seen.has(k)) {
        seen.add(k);
        keys.push(k);
      }
    }
  }
  const out: RuntimePack = { keys, langs: {} };
  for (const l of langs) out.langs[l] = keys.map((k) => (Object.prototype.hasOwnProperty.call(cleaned[l], k) ? cleaned[l][k]! : null));
  return out;
}

/**
 * 產生 renderer 端要執行的完整腳本（自足、零依賴）。
 * @param dict    apply 語系（`options.lang`）的詞庫
 * @param extra   其他語系的詞庫：一併打包，讓面板可以免重整切換（apply 語系一律以 dict 為準）
 */
export function buildRuntimeScript(dict: Dictionary, options: OverlayOptions, extra: RuntimeDicts = {}): string {
  const fn = antigravityI18nOverlay.toString();
  const dicts: RuntimeDicts = { ...extra, [options.lang as Lang]: dict };
  // 不在 LANGS 內的語系（理論上不會發生）退回單一語系字典
  const data = (LANGS as readonly string[]).includes(options.lang) ? buildRuntimePack(dicts) : runtimeDictionary(dict);
  return [
    RUNTIME_MARKER,
    `/* Generated by antigravity-i18n ${options.version} (${options.lang}). Do not edit. */`,
    `;(${fn})(${JSON.stringify(data)}, ${JSON.stringify(options)});`,
    '',
  ].join('\n');
}

/** runtime 檔內打包了哪些語系 */
export function runtimeLangs(dict: Dictionary, lang: Lang, extra: RuntimeDicts = {}): Lang[] {
  return LANGS.filter((l) => l === lang || (extra[l] !== undefined && Object.keys(runtimeDictionary(extra[l]!)).length > 0));
}

/**
 * 判斷 webContents 的網址是否為 App 自己的內部頁面（才注入 runtime）。
 *
 * - 允許：`file:`、App 自訂的內部 scheme（如 `app:`、`antigravity:`），以及本機的
 *   `http:` / `https:`（`localhost`、`127.0.0.1`、`[::1]`）
 * - 略過：外部 `http:` / `https:` 網站（例如內建瀏覽器開啟的網頁）、`devtools:`、
 *   `chrome:`、`chrome-extension:`、`chrome-error:`、`about:`、`view-source:`、`data:`
 * - `blob:` 依其來源網址判斷；無法解析的網址一律略過
 *
 * ⚠️ 此函式會以 `toString()` 內嵌進主行程掛鉤，必須完全自足。
 */
export function isInternalUrl(url: string): boolean {
  if (typeof url !== 'string' || url === '') return false;
  const m = /^([a-z][a-z0-9+.-]*):/i.exec(url);
  if (!m || !m[1]) return false;
  const scheme = m[1].toLowerCase();
  if (['devtools', 'chrome', 'chrome-extension', 'chrome-error', 'about', 'view-source', 'data', 'javascript'].includes(scheme)) {
    return false;
  }
  if (scheme === 'blob') return isInternalUrl(url.slice(m[0].length));
  if (scheme !== 'http' && scheme !== 'https') return true;
  let host: string;
  try {
    host = new URL(url).hostname.toLowerCase();
  } catch {
    return false;
  }
  return host === 'localhost' || host === '127.0.0.1' || host === '[::1]';
}

/** 將自足函式序列化，並把遞迴呼叫改成掛鉤內的變數名稱 */
function inlineFn(fn: (...args: never[]) => unknown, as: string): string {
  // 以 fn.name 取得實際名稱：esbuild 打包時可能為避免衝突而改名（例如 isInternalUrl2）
  const name = fn.name;
  return fn
    .toString()
    .replace(new RegExp(`\\b${name}\\(`, 'g'), `${as}(`)
    .replace(new RegExp(`^function ${as}\\(`), 'function (');
}

/** 主行程掛鉤共用邏輯（CJS / ESM 變體共用） */
function installSource(): string {
  return `var __agi18nIsInternalUrl = ${inlineFn(isInternalUrl, '__agi18nIsInternalUrl')};
    var __agi18nReadBg = ${inlineFn(readBackgroundPayload, '__agi18nReadBg')};
    var __agi18nApplyBg = ${JSON.stringify(applyBackground.toString())};
    var __agi18nPresets = ${JSON.stringify(presetImages())};
    var __agi18nPanel = ${JSON.stringify(antigravityI18nPanel.toString())};
    var __agi18nPanelPresets = ${JSON.stringify(presetMeta())};
    var __agi18nPanelI18n = ${JSON.stringify(panelI18n())};
    function __agi18nInstall(app, code, readBg) {
    if (!app || (!code && !readBg) || globalThis.__ANTIGRAVITY_I18N_HOOK__) return;
    globalThis.__ANTIGRAVITY_I18N_HOOK__ = ${HOOK_VERSION};
    var inject = function (wc, js, what) {
      Promise.resolve(wc.executeJavaScript(js, true)).catch(function (err) {
        console.warn('[antigravity-i18n] ' + what + ' inject failed:', err && err.message);
      });
    };
    app.on('web-contents-created', function (_event, wc) {
      var type = '';
      try { type = wc.getType(); } catch (e) {}
      // 只注入應用程式自己的視窗，不注入 <webview>、DevTools 與背景頁
      if (type !== 'window' && type !== 'browserView') return;
      wc.on('dom-ready', function () {
        var url = '';
        try { url = wc.getURL(); } catch (e) {}
        // 每次載入都重新判斷：視窗導向外部網站時不注入
        if (!__agi18nIsInternalUrl(url)) return;
        if (code) inject(wc, code, 'runtime');
        // 自訂背景圖：每次載入重新讀取設定，換圖不需重新打包；任何錯誤都不影響翻譯
        if (readBg && process.env.ANTIGRAVITY_I18N_NO_BG !== '1') {
          var bg = null;
          try { bg = readBg(); } catch (e) { console.warn('[antigravity-i18n] background:', e && e.message); }
          if (process.env.ANTIGRAVITY_I18N_NO_PANEL === '1') {
            // 停用介面面板：只套用 CLI 設定
            if (bg) inject(wc, '(' + __agi18nApplyBg + ')(' + JSON.stringify(bg) + ');', 'background');
          } else {
            // 介面面板（Ctrl+Alt+B）：即使沒有 CLI 設定也注入，讓使用者隨時能在介面中設定
            var panelCfg = { cli: bg, presets: __agi18nPanelPresets, maxBytes: ${PANEL_MAX_BYTES}, version: ${HOOK_VERSION}, i18n: __agi18nPanelI18n };
            inject(wc, '(function(){var applyBackground=' + __agi18nApplyBg + ';(' + __agi18nPanel + ')(applyBackground,' + JSON.stringify(panelCfg) + ');})();', 'background panel');
          }
        }
      });
    });
  }`;
}

/** 產生主行程掛鉤程式碼 */
export function buildHook(format: ModuleFormat, runtimeFileName = RUNTIME_FILE_NAME, opts: HookOptions = {}): string {
  const file = JSON.stringify(`./${runtimeFileName}`);
  const translate = opts.translate !== false;
  const version = `/* antigravity-i18n:hook-version ${HOOK_VERSION}${translate ? '' : ' background-only'} */`;
  if (format === 'esm') {
    return `${HOOK_BEGIN}
${version}
import * as __agi18nElectron from 'electron';
import * as __agi18nFs from 'node:fs';
import * as __agi18nOs from 'node:os';
import * as __agi18nPath from 'node:path';
import * as __agi18nUrl from 'node:url';
;(function () {
  try {
    if (process.env.ANTIGRAVITY_I18N_DISABLE === '1') return;
    var mod = function (ns) { return ns.default || ns; };
    var electron = mod(__agi18nElectron);
    var app = __agi18nElectron.app || electron.app;
    var fs = mod(__agi18nFs), os = mod(__agi18nOs), path = mod(__agi18nPath);
    ${installSource()}
    var code = '';
    ${
      translate
        ? `try {
      code = fs.readFileSync(mod(__agi18nUrl).fileURLToPath(new URL(${file}, import.meta.url)), 'utf8');
    } catch (e) {
      console.warn('[antigravity-i18n] runtime not loaded:', e && e.message);
    }`
        : '// 僅背景模式：不載入翻譯 runtime'
    }
    var bgCache = {};
    __agi18nInstall(app, code, function () { return __agi18nReadBg(fs, path, os, process.env, process.platform, bgCache, __agi18nPresets); });
  } catch (e) {
    console.warn('[antigravity-i18n] runtime hook disabled:', e && e.message);
  }
})();
${HOOK_END}
`;
  }
  return `${HOOK_BEGIN}
${version}
;(function () {
  try {
    if (process.env.ANTIGRAVITY_I18N_DISABLE === '1') return;
    ${installSource()}
    var fs = require('fs'), path = require('path'), os = require('os');
    var code = '';
    ${
      translate
        ? `try {
      code = fs.readFileSync(path.join(__dirname, ${file}), 'utf8');
    } catch (e) {
      console.warn('[antigravity-i18n] runtime not loaded:', e && e.message);
    }`
        : '// 僅背景模式：不載入翻譯 runtime'
    }
    var bgCache = {};
    __agi18nInstall(require('electron').app, code, function () { return __agi18nReadBg(fs, path, os, process.env, process.platform, bgCache, __agi18nPresets); });
  } catch (e) {
    console.warn('[antigravity-i18n] runtime hook disabled:', e && e.message);
  }
})();
${HOOK_END}
`;
}

export function hasHook(code: string): boolean {
  return code.includes(HOOK_BEGIN);
}

/** 移除先前注入的掛鉤（讓注入具冪等性） */
export function stripHook(code: string): string {
  let out = code;
  for (;;) {
    const start = out.indexOf(HOOK_BEGIN);
    if (start < 0) return out;
    const end = out.indexOf(HOOK_END, start);
    if (end < 0) return out;
    let stop = end + HOOK_END.length;
    if (out[stop] === '\n') stop++;
    out = out.slice(0, start) + out.slice(stop);
  }
}

/**
 * 在主行程入口最前面插入掛鉤，確保在 App 建立任何視窗之前就完成註冊。
 * 會保留 shebang 與 `'use strict'` 指示詞的位置（指示詞必須是第一個敘述）。
 */
export function injectHook(code: string, format: ModuleFormat, runtimeFileName = RUNTIME_FILE_NAME, opts: HookOptions = {}): string {
  const clean = stripHook(code);
  const prologue = clean.match(/^(?:#![^\n]*\n)?(?:\s*(?:\/\/[^\n]*\n|\/\*[\s\S]*?\*\/))*\s*(["'])use strict\1;?[^\S\n]*\n?/);
  const shebang = clean.match(/^#![^\n]*\n/);
  const at = prologue ? prologue[0].length : shebang ? shebang[0].length : 0;
  const head = clean.slice(0, at);
  return `${head}${head && !head.endsWith('\n') ? '\n' : ''}${buildHook(format, runtimeFileName, opts)}${clean.slice(at)}`;
}

interface PackageJsonLike {
  main?: unknown;
  type?: unknown;
}

export function parsePackageJson(text: string): PackageJsonLike | null {
  try {
    const v = JSON.parse(text.replace(/^﻿/, '')) as unknown;
    return v && typeof v === 'object' ? (v as PackageJsonLike) : null;
  } catch {
    return null;
  }
}

/** 依 package.json 的 `main` 找出主行程入口（asar 內相對路徑，`/` 分隔） */
export function resolveMainEntry(pkg: PackageJsonLike | null, files: ReadonlySet<string>): string | null {
  const raw = typeof pkg?.main === 'string' && pkg.main.trim() !== '' ? pkg.main.trim() : 'index.js';
  const main = path.posix.normalize(raw.replace(/\\/g, '/')).replace(/^(\.\/)+/, '').replace(/\/$/, '');
  if (main.startsWith('..')) return null;
  for (const c of [main, `${main}.js`, `${main}.cjs`, `${main}.mjs`, `${main}/index.js`]) if (files.has(c)) return c;
  return null;
}

export function detectModuleFormat(mainEntry: string, pkg: PackageJsonLike | null): ModuleFormat {
  if (mainEntry.endsWith('.mjs')) return 'esm';
  if (mainEntry.endsWith('.cjs')) return 'cjs';
  return pkg?.type === 'module' ? 'esm' : 'cjs';
}

/** runtime 檔案放在主行程入口旁，掛鉤以相對路徑讀取 */
export function runtimeEntryPath(mainEntry: string): string {
  const dir = path.posix.dirname(mainEntry);
  return dir === '.' ? RUNTIME_FILE_NAME : `${dir}/${RUNTIME_FILE_NAME}`;
}
