export function panelI18n(): Record<PanelLang, PanelText> {
  return JSON.parse(JSON.stringify(PANEL_TEXT)) as Record<PanelLang, PanelText>;
}

/** 依瀏覽器語系挑選面板語系（與面板內的規則相同，測試逐一比對） */
export function panelLangFromNavigator(language: string | undefined): PanelLang {
  const v = (language ?? '').toLowerCase();
  if (/^zh-(?:tw|hk|mo)(?:-|$)|^zh-hant(?:-|$)/.test(v)) return 'zh-TW';
  if (/^zh(?:-|$)/.test(v)) return 'zh-CN';
  if (/^ja(?:-|$)/.test(v)) return 'ja';
  if (/^ko(?:-|$)/.test(v)) return 'ko';
  return 'en';
}
